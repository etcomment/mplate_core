import { mkdirSync, writeFileSync } from 'node:fs'
import { formatCard, listTemplates, render, syntaxGuide } from '../dist/index.js'

const galleryDirectory = new URL('../docs/gallery/', import.meta.url)
mkdirSync(galleryDirectory, { recursive: true })

const sections = []
for (const card of listTemplates()) {
  const fileName = `${card.id.replace(':', '-')}.svg`
  const result = render(card.example)
  if (!result.ok) throw new Error(`${card.id} example failed: ${JSON.stringify(result.diagnostics)}`)
  writeFileSync(new URL(fileName, galleryDirectory), result.svg)
  sections.push(`${formatCard(card)}\n\n![${card.name}](gallery/${fileName})\n`)
}

const dark = render(listTemplates().find((card) => card.id === 'brain:spokes').example, { theme: 'dark' })
writeFileSync(new URL('brain-spokes-dark.svg', galleryDirectory), dark.svg)

const header = `# Template catalogue

Generated by \`npm run gallery\` from the identity cards in \`src/templates\`. Do not edit by hand.

${listTemplates().length} templates in ${new Set(listTemplates().map((card) => card.family)).size} families.

| Template | Elements | Good for |
| --- | --- | --- |
${listTemplates().map((card) => `| \`${card.id}\` | ${card.items.min}–${card.items.max} | ${card.useCases.join(', ')} |`).join('\n')}

`
writeFileSync(new URL('../docs/templates.md', import.meta.url), header + sections.join('\n'))
writeFileSync(new URL('../docs/llm-guide.md', import.meta.url), `<!-- Generated by npm run gallery. This is the text returned by the mplate_guide MCP tool and \`mplate guide\`. -->\n\n${syntaxGuide()}\n`)
console.log(`Gallery: ${listTemplates().length} templates`)
